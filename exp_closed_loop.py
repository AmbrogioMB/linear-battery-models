"""
exp_closed_loop.py

Experiment 2: sequential (closed-loop) operation of the battery over several
months of real data, with the state of charge carried over from one period to
the next. At each 15-minute period t the policy observes the realized load,
PV generation and carbon intensity up to t-1 and its current state of charge,
and decides the battery power for period t. Realized emissions are computed
with the actual data.

Policies:
  NB      no battery;
  AB      rule-based self-consumption;
  EV-RH   receding horizon, deterministic (expected-value) forecast;
  PB-RH   receding horizon, Programmed Battery on M scenarios;
  2S-RH   receding horizon, two-stage stochastic model on M scenarios;
  PB-DA   Programmed Battery solved once per day (day-ahead schedule);
  FBk-DA  Feedback Battery (k in 2, 3) solved once per day, affine rule applied online;
  PF      perfect foresight over the whole period (lower bound).
The suffix "-RT" (e.g. PB-RT) denotes the real-time information variant of the
receding-horizon policies, in which the load, PV generation and carbon
intensity of the current period are observed before deciding (as in AB).

Scenarios are generated by the PCA model fitted on the 28 days preceding the
current day; the profile of the current day is sampled conditionally on the
values observed so far, the next day unconditionally.

Usage: python exp_closed_loop.py <policy> [--bmax B --pb P --load S]
(the options define a sensitivity configuration, see configure()).
Runs are checkpointed every day and resumed automatically if interrupted.
"""
import os
import sys
import time
import numpy as np
import gurobipy as gp
from gurobipy import GRB
import core
from core import (T, DT, P_B, B_MAX, ETA, MU, P_MAX, BETA, CYCLE_BUDGET, ScenarioModel, ab_step,
                  solve_pb, solve_fb, fb_policy, fb_features)

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results_cl")
os.makedirs(RES, exist_ok=True)

FIRST, LAST = "2026-02-01", "2026-10-19"
WINDOW_DAYS = 28
K = 5
M_RH = 100       # scenarios per receding-horizon decision
M_DA = 500       # scenarios for the day-ahead models
E_INIT = B_MAX / 2
SEED = 7
EPS = 1e-3       # tie-breaking reward on stored energy [gCO2e per kWh and period]

d = np.load(os.path.join(HERE, "data", "dataset.npz"))
DATES, LOAD, SOLAR, ALPHA = d["dates"], d["load"], d["solar"], d["alpha"]
D0 = int(np.where(DATES == FIRST)[0][0])
D1 = int(np.where(DATES == LAST)[0][0])
DAYS = range(D0, D1 + 1)


def model_for_day(day):
    w = slice(day - WINDOW_DAYS, day)
    return ScenarioModel(LOAD[w], SOLAR[w], ALPHA[w], K=K)


def window_scenarios(sm, day, tau, n, realtime=False):
    """
    Scenarios (n, T) for the window [tau of today, tau of tomorrow), conditioned
    on the observations of today up to tau-1 (ex-ante information) or up to tau
    (real-time information: the first period of the window is known).
    """
    rng = np.random.default_rng([SEED, day, tau])
    k = tau + 1 if realtime else tau
    lt, st, at = sm.sample_conditional(LOAD[day, :k], SOLAR[day, :k], ALPHA[day, :k], n, rng)
    if tau == 0:
        return lt, st, at
    e = np.zeros(0)
    ln, sn, an = sm.sample_conditional(e, e, e, n, rng)
    return (np.hstack([lt[:, tau:], ln[:, :tau]]), np.hstack([st[:, tau:], sn[:, :tau]]),
            np.hstack([at[:, tau:], an[:, :tau]]))


class RecedingLP:
    """
    Receding-horizon LP (PB or two-stage) built once and updated at every
    period (right-hand sides, objective coefficients and bounds only).
    The cycle limit is imposed per calendar day through cumulative throughput
    variables G_k: G_k <= remaining budget of today for the steps of today,
    G_k <= remaining budget + full budget for the steps of tomorrow.
    """

    def __init__(self, M, two_stage):
        self.M, self.two = M, two_stage
        H = T
        m = gp.Model(env=core.env())
        self.yp = m.addMVar((M, H), lb=0, ub=P_MAX)
        self.ym = m.addMVar((M, H), lb=0, ub=P_MAX)
        if two_stage:
            bp = m.addMVar((M, H), lb=0, ub=MU * P_B)
            bm = m.addMVar((M, H), lb=0, ub=P_B)
            m.addConstr(bp[1:, 0] == bp[0, 0]); m.addConstr(bm[1:, 0] == bm[0, 0])
            E = m.addMVar((M, H + 1), lb=0, ub=B_MAX)
            m.addConstr(E[:, 1:] == E[:, :-1] + DT * (ETA * bm - bp / MU))
            self.e0 = m.addConstr(E[:, 0] == np.full(M, E_INIT))
            G = m.addMVar((M, H), lb=0)
            m.addConstr(G[:, 0] == DT * (bp[:, 0] / MU + ETA * bm[:, 0]))
            m.addConstr(G[:, 1:] == G[:, :-1] + DT * (bp[:, 1:] / MU + ETA * bm[:, 1:]))
            self.bal = m.addConstr(self.yp - self.ym + bp - bm == np.zeros((M, H)))
            obj_b = BETA * DT / (MU * M) * bp.sum() - (EPS / M) * E[:, 1:].sum()
        else:
            bp = m.addMVar(H, lb=0, ub=MU * P_B)
            bm = m.addMVar(H, lb=0, ub=P_B)
            E = m.addMVar(H + 1, lb=0, ub=B_MAX)
            m.addConstr(E[1:] == E[:-1] + DT * (ETA * bm - bp / MU))
            self.e0 = m.addConstr(E[0] == E_INIT)
            G = m.addMVar(H, lb=0)
            m.addConstr(G[0] == DT * (bp[0] / MU + ETA * bm[0]))
            m.addConstr(G[1:] == G[:-1] + DT * (bp[1:] / MU + ETA * bm[1:]))
            self.bal = m.addConstr(self.yp - self.ym + bp[None, :] - bm[None, :] == np.zeros((M, H)))
            obj_b = BETA * DT / MU * bp.sum() - EPS * E[1:].sum()
        m.setObjective(obj_b, GRB.MINIMIZE)
        m.Params.Method = 1 if two_stage else 0  # fastest re-solve methods in preliminary tests
        self.m, self.bp, self.bm, self.G = m, bp, bm, G

    def solve(self, L, S, A, E0, rem_today, tau):
        H = T
        self.bal.RHS = L - S
        self.yp.Obj = (DT / self.M) * A
        if self.two:
            self.e0.RHS = np.full(self.M, E0)
        else:
            self.e0.RHS = E0
        split = H - tau  # first index belonging to tomorrow
        ub = np.where(np.arange(H) < split, rem_today, rem_today + CYCLE_BUDGET)
        self.G.UB = np.broadcast_to(ub, self.G.shape)
        self.m.optimize()
        if self.m.Status != GRB.OPTIMAL:
            self.m.reset()
            self.m.optimize()
        if self.two:
            return float(self.bp.X[0, 0]), float(self.bm.X[0, 0]), self.m.Runtime
        return float(self.bp.X[0]), float(self.bm.X[0]), self.m.Runtime


def project(rp, rm, E, rem):
    p = min(max(rp, 0.0), MU * P_B, MU * E / DT, rem * MU / DT)
    m = min(max(rm, 0.0), P_B, (B_MAX - E) / (DT * ETA), max(rem - DT * p / MU, 0) / (DT * ETA))
    return max(p, 0.0), max(m, 0.0)


def run(policy):
    out = os.path.join(RES, f"{policy}.npz")
    nD = len(DAYS)
    BP = np.zeros((nD, T)); BM = np.zeros((nD, T)); EE = np.zeros((nD, T + 1))
    times = []
    E = E_INIT
    lp = None
    realtime = policy.endswith("-RT")
    if policy[:2] in ("PB", "EV") and policy[3:] in ("RH", "RT"):
        lp = RecedingLP(1 if policy.startswith("EV") else M_RH, two_stage=False)
    elif policy in ("2S-RH", "2S-RT"):
        lp = RecedingLP(M_RH, two_stage=True)
    start = 0
    if os.path.isfile(out):  # resume from the last checkpoint
        z = np.load(out)
        start = len(z["em"])
        if start >= nD:
            print(f"{policy}: already complete")
            return
        BP[:start], BM[:start], EE[:start] = z["bp"], z["bm"], z["E"]
        times = list(z["times"])
        E = float(EE[start - 1, -1])
        print(f"{policy}: resuming from day {start}")
    t_start = time.time()
    for i, day in enumerate(DAYS):
        if i < start:
            continue
        used = 0.0
        EE[i, 0] = E
        sm = model_for_day(day) if policy not in ("NB", "AB") else None
        da_policy = None
        if policy == "PB-DA" or policy.startswith("FB"):
            l, s, a = window_scenarios(sm, day, 0, M_DA)
            target = solve_pb(l, s, a, E0=None, cyclic=True, soc_reward=EPS)["E"][0]
            if policy == "PB-DA":
                r = solve_pb(l, s, a, E0=E, E_end=target, soc_reward=EPS)
                da_policy = ("sched", r["bp"], r["bm"]); times.append(r["time"])
            else:
                kind = policy.split("-")[0]
                r = solve_fb(kind, l, s, a, E0=E, E_end=target, soc_reward=EPS)
                if r is None:  # fall back to the programmed schedule
                    r2 = solve_pb(l, s, a, E0=E, E_end=target, soc_reward=EPS)
                    da_policy = ("sched", r2["bp"], r2["bm"])
                else:
                    da_policy = ("fb", kind, r["coef"])
                times.append(r["time"] if r else np.nan)
        for tau in range(T):
            rem = max(CYCLE_BUDGET - used, 0.0)
            net = LOAD[day, tau] - SOLAR[day, tau]
            if policy == "NB":
                p, m_ = 0.0, 0.0
            elif policy == "AB":
                p, m_ = ab_step(np.array([E]), np.array([net]), np.array([used]), budget=CYCLE_BUDGET)
                p, m_ = float(p[0]), float(m_[0])
            elif lp is not None:
                L, S, A = window_scenarios(sm, day, tau, M_RH, realtime)
                if policy.startswith("EV"):
                    L, S, A = L.mean(0, keepdims=True), S.mean(0, keepdims=True), A.mean(0, keepdims=True)
                rp, rm, rt = lp.solve(L, S, A, E, rem, tau)
                times.append(rt)
                p, m_ = project(rp, rm, E, rem)
            elif da_policy[0] == "sched":
                p, m_ = project(da_policy[1][tau], da_policy[2][tau], E, rem)
            else:
                kind, coef = da_policy[1], da_policy[2]
                pol = fb_policy(kind, coef)
                rp, rm = pol(tau, LOAD[day:day + 1], SOLAR[day:day + 1])
                p, m_ = project(float(np.ravel(rp)[0]), float(np.ravel(rm)[0]), E, rem)
            BP[i, tau], BM[i, tau] = p, m_
            used += DT * (p / MU + ETA * m_)
            E = min(max(E + DT * (ETA * m_ - p / MU), 0.0), B_MAX)
            EE[i, tau + 1] = E
        save(out, BP, BM, EE, times, i + 1)  # daily checkpoint
        if i % 10 == 0 or i == nD - 1:
            print(f"{policy} {DATES[day]} E={E:.2f} elapsed {time.time() - t_start:.0f}s", flush=True)
    save(out, BP, BM, EE, times, nD)


def save(out, BP, BM, EE, times, n):
    idx = np.array(DAYS)[:n]
    y = LOAD[idx] - SOLAR[idx] - BP[:n] + BM[:n]
    em = DT * (ALPHA[idx] * np.maximum(y, 0)).sum(1) + BETA * DT * BP[:n].sum(1) / MU
    np.savez(out, days=DATES[idx], bp=BP[:n], bm=BM[:n], E=EE[:n], em=em, times=np.array(times),
             viol=(np.maximum(y, 0) > P_MAX + 1e-6).sum() + (np.maximum(-y, 0) > P_MAX + 1e-6).sum())


def run_pf():
    """Perfect-foresight benchmark: one LP over the whole period with actual data."""
    idx = np.array(DAYS)
    l, s, a = LOAD[idx].ravel(), SOLAR[idx].ravel(), ALPHA[idx].ravel()
    N = len(l)
    m = gp.Model(env=core.env())
    bp = m.addMVar(N, lb=0, ub=MU * P_B)
    bm = m.addMVar(N, lb=0, ub=P_B)
    E = m.addMVar(N + 1, lb=0, ub=B_MAX)
    m.addConstr(E[1:] == E[:-1] + DT * (ETA * bm - bp / MU))
    m.addConstr(E[0] == E_INIT)
    yp = m.addMVar(N, lb=0, ub=P_MAX)
    ym = m.addMVar(N, lb=0, ub=P_MAX)
    m.addConstr(yp - ym + bp - bm == l - s)
    nD = len(idx)
    m.addConstr(DT * (bp.reshape(nD, T).sum(axis=1) / MU + ETA * bm.reshape(nD, T).sum(axis=1)) <= CYCLE_BUDGET)
    m.setObjective(DT * (a @ yp) + BETA * DT / MU * bp.sum(), GRB.MINIMIZE)
    m.optimize()
    EE = np.zeros((nD, T + 1))
    Ex = E.X
    for i in range(nD):
        EE[i] = Ex[i * T:(i + 1) * T + 1]
    save(os.path.join(RES, "PF.npz"), bp.X.reshape(nD, T), bm.X.reshape(nD, T), EE, [m.Runtime], nD)
    print("PF", m.ObjVal, m.Runtime)


def configure(b_max, p_b, load_scale):
    """
    Sensitivity analysis: change the battery capacity [kWh] and power [kW] and
    scale the household load. Results go to results_cl_sens/B<b>_P<p>_L<s>/.
    """
    global B_MAX, P_B, CYCLE_BUDGET, E_INIT, LOAD, RES
    B_MAX, P_B = b_max, p_b
    CYCLE_BUDGET = 2 * core.C_CYC * b_max
    core.B_MAX, core.P_B, core.CYCLE_BUDGET = B_MAX, P_B, CYCLE_BUDGET
    E_INIT = b_max / 2
    LOAD = LOAD * load_scale
    RES = os.path.join(HERE, "results_cl_sens", f"B{b_max:g}_P{p_b:g}_L{load_scale:g}")
    os.makedirs(RES, exist_ok=True)


if __name__ == "__main__":
    # usage: python exp_closed_loop.py <policy> [--bmax B --pb P --load S]
    pol = sys.argv[1]
    opts = dict(zip(sys.argv[2::2], map(float, sys.argv[3::2])))
    if opts:
        configure(opts.get("--bmax", B_MAX), opts.get("--pb", P_B), opts.get("--load", 1.0))
    if pol == "PF":
        run_pf()
    else:
        run(pol)
